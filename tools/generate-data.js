// --- Уақыт бойынша салмақ ---
const yearOf = m => START.y + (START.m - 1 + m) / 12; // бөлшек жыл
function skillWeight(k, t) {
  const [, , w0, g, logi] = skills[k];
  if (logi) return w0 / (1 + Math.exp(-2.2 * (t - logi))) + 0.02; // жаңа технология: S-қисық
  return w0 * Math.exp(g * (t - 2020));
}
function covid(t) { // 2020 жылдың көктемгі құлдырауы
  return t >= 2020.17 && t < 2020.6 ? 0.68 : 1;
}

// --- Генерация ---
const TOTAL = 104000;
const base = TOTAL / MONTHS;
const vac = [];
for (let m = 0; m < MONTHS; m++) {
  const t = yearOf(m);
  const month = (START.m - 1 + m) % 12;
  const season = 1 + 0.08 * Math.cos((month - 3) / 12 * 2 * Math.PI) - (month === 0 ? 0.12 : 0);
  const n = Math.round(base * 0.82 * Math.pow(1.055, t - 2020) * covid(t) * season * (1 + 0.05 * gauss()));
  const secW = sectors.map(s => s[1] * Math.exp(s[2] * (t - 2020)));
  // лауазым салмағы = негізгі дағдыларының қазіргі салмағы
  const titleW = titles.map(([, , ks]) => ks.reduce((a, k) => a + skillWeight(K[k], t), 0) / ks.length);

  for (let i = 0; i < n; i++) {
    const sec = pickW(sectors.map((_, j) => j), secW);
    const secName = sectors[sec][0];
    const tIdx = titles.map((x, j) => j).filter(j => titles[j][1] === secName);
    const ti = pickW(tIdx, tIdx.map(j => titleW[j]));
    const [, , core] = titles[ti];

    // дағдылар: лауазымның негізгі дағдылары + саланың басқа дағдылары + жалпы дағдылар
    const chosen = new Set();
    core.forEach(k => { if (rnd() < 0.55 + 0.35 * Math.min(1, skillWeight(K[k], t) / 1.2)) chosen.add(K[k]); });
    const pool = skills.map((_, k) => k).filter(k => !chosen.has(k) &&
      (skills[k][1].includes(secName) || skills[k][1][0] === '*'));
    const extra = 1 + Math.floor(rnd() * 3);
    for (let e = 0; e < extra && pool.length; e++) {
      // дағды өзінің негізгі (бірінші) саласынан тыс сирек кездеседі
      const k = pickW(pool, pool.map(k => skillWeight(k, t) * (skills[k][1][0] === '*' ? 0.5 : skills[k][1][0] === secName ? 1 : 0.3)));
      chosen.add(k); pool.splice(pool.indexOf(k), 1);
    }
    if (!chosen.size) chosen.add(K[core[0]]);

    const exp = pickW([0, 1, 2, 3], [0.22, 0.42, 0.26, 0.10]);
    const src = pickW([0, 1, 2], [0.58, 0.14, 0.28]);
    const expMul = [0.72, 1, 1.3, 1.65][exp];
    const reg = pickW(regions.map((_, j) => j), regions.map(r => r[1]));
    const premium = [...chosen].reduce((a, k) => a + skills[k][5], 0) / Math.max(1, chosen.size);
    const salary = sectors[sec][3] * regions[reg][2] * Math.pow(1.085, t - 2020) *
      (1 + premium * 1.5) * Math.exp(0.22 * gauss());
    const comp = companyList.indexOf(companies[secName][Math.floor(rnd() * companies[secName].length)]);

    vac.push([m, reg, sec, ti, comp, Math.round(salary * expMul / 5) * 5, [...chosen].sort((a, b) => a - b), src, exp]);
  }
}

